type PolicyKind = "privacy" | "terms" | null;

export function PolicyModal({ kind, onClose }: { kind: PolicyKind; onClose: () => void }) {
  if (!kind) return null;
  return (
    <div className="policy-overlay" onClick={onClose}>
      <div className="policy-sheet" onClick={(e) => e.stopPropagation()}>
        {kind === "privacy" ? <PrivacyDraft /> : <TermsDraft />}
        <button className="btn" style={{ marginTop: 18 }} onClick={onClose}>
          닫기
        </button>
      </div>
    </div>
  );
}

